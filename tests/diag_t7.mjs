import { connect } from './cdp.mjs'
const c = await connect()
await c.send('Page.enable'); await c.send('Page.reload', { ignoreCache: true }); await c.wait(3000)
await c.clickText('button.nav-item', 'Temas'); await c.wait(500)
await c.typeInput('input[placeholder="Ex.: Meu tema verde"]', 'Tema diag')
await c.wait(400)
console.log('NAME', await c.evaluate(`document.querySelector('input[placeholder="Ex.: Meu tema verde"]')?.value`))
console.log('SAVE BTNS', await c.evaluate(`[...document.querySelectorAll('button')].filter(b=>b.textContent.trim()==='Salvar').length`))
await c.evaluate(`(()=>{const b=[...document.querySelectorAll('button')].find(x=>x.textContent.trim()==='Salvar');if(b)b.click()})()`)
await c.wait(700)
console.log('THEMES', await c.evaluate(`(async()=>JSON.stringify(await window.api.db.all('SELECT name FROM themes')))()`))
await c.send('Input.dispatchKeyEvent', { type:'keyDown', key:'k', code:'KeyK', modifiers:2, windowsVirtualKeyCode:75 }); await c.send('Input.dispatchKeyEvent', { type:'keyUp', key:'k', code:'KeyK', modifiers:2, windowsVirtualKeyCode:75 })
await c.wait(600)
await c.typeInput('.search-input-row input', 'Música')
await c.wait(600)
console.log('SEARCH', await c.evaluate(`JSON.stringify({val:document.querySelector('.search-input-row input')?.value,results:document.querySelectorAll('.search-result').length,body:document.querySelector('.search-modal')?.innerText.slice(0,200)})`))
c.close()
