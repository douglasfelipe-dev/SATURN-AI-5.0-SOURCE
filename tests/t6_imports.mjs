import { connect, check, summary } from './cdp.mjs'
import path from 'node:path'
const c = await connect()
const pdf = path.resolve('tests/fixtures/livro.pdf')
const foto = path.resolve('tests/fixtures/foto.jpg')
const foto2 = path.resolve('tests/fixtures/foto2.png')
const doc = path.resolve('tests/fixtures/documento.txt')
const video = path.resolve('../video/2026-11-19 15-27-01.mp4')
await c.send('Page.enable')
await c.send('Page.reload', { ignoreCache: true })
await c.wait(3000)

// Biblioteca (drag & drop)
await c.clickText('button.nav-item', 'Livros')
await c.wait(500)
await c.dropFiles('.page', [pdf, pdf])
await c.wait(3500)
const books = await c.evaluate(`(async()=>{const r=await window.api.db.all('SELECT COUNT(*) c FROM books');return r.rows[0].c})()`)
check('PDFs importados por arrastar e soltar', books >= 1, `${books} livros`)
check('livro aparece na grade', await c.evaluate(`!!document.querySelector('.book-card')`))
await c.evaluate(`document.querySelector('.book-card')?.click()`)
await c.wait(1800)
check('leitor de PDF abriu e renderizou', await c.evaluate(`!!document.querySelector('.pdf-viewer canvas')`))
await c.evaluate(`document.querySelector('.pdf-toolbar .btn.icon')?.click()`)
await c.wait(400)

// Galeria
await c.clickText('button.nav-item', 'Galeria de fotos')
await c.wait(500)
await c.dropFiles('.page', [foto, foto2])
await c.wait(2500)
const fotos = await c.evaluate(`(async()=>{const r=await window.api.db.all('SELECT COUNT(*) c FROM photos');return r.rows[0].c})()`)
check('fotos importadas por arrastar e soltar', fotos >= 2, String(fotos))
check('fotos exibidas na galeria', (await c.evaluate(`document.querySelectorAll('.media-card').length`)) >= 2)
await c.evaluate(`document.querySelector('.media-card')?.click()`)
await c.wait(700)
check('visualizador de imagem abriu', await c.evaluate(`!!document.querySelector('.lightbox img')`))
await c.evaluate(`document.querySelectorAll('.lightbox .lb-btn')[5]?.click()`)
await c.wait(400)

// Arquivos
await c.clickText('button.nav-item', 'Arquivos')
await c.wait(500)
await c.dropFiles('.page', [doc, pdf])
await c.wait(2500)
const arquivos = await c.evaluate(`(async()=>{const r=await window.api.db.all('SELECT COUNT(*) c FROM files');return r.rows[0].c})()`)
check('arquivos importados', arquivos >= 2, String(arquivos))
check('arquivos listados', (await c.evaluate(`document.querySelectorAll('.file-row').length`)) >= 2)

// Vídeos locais
await c.clickText('button.nav-item', 'Vídeos')
await c.wait(500)
await c.dropFiles('.page', [video])
await c.wait(3500)
const vids = await c.evaluate(`(async()=>{const r=await window.api.db.all('SELECT COUNT(*) c FROM local_videos');return r.rows[0].c})()`)
check('vídeo local importado', vids >= 1, String(vids))
check('player de vídeo local existe', await c.evaluate(`!!document.querySelector('.page video')`))

summary('T6 IMPORTAÇÕES')
c.close()
